#!/usr/bin/env bash
# Compiles src/render3d/shaders.hlsl (the 3D mode's HLSL shaders) to SPIR-V for SDL_gpu's Vulkan
# backend and writes src/render3d/shaders_spirv.inc (checked in, so no build needs a shader
# compiler). Run after every change to shaders.hlsl (keep shaders_msl.hpp / models_msl.hpp in step).
#
# Needs glslangValidator (Homebrew: `brew install glslang`; Linux: glslang-tools; also in the
# Vulkan SDK) and, optionally, spirv-val (spirv-tools) to validate the modules.
#   tools/compile_shaders.sh            # regenerate the .inc
#   tools/compile_shaders.sh --check    # compile + validate only, leave the .inc alone
#
# --auto-sampled-textures: SDL_gpu's Vulkan backend binds every fragment texture slot as a
# COMBINED image sampler (set 2, binding n); glslang folds each Texture t[n] + SamplerState s[n]
# pair of the HLSL into one. Register spaces become descriptor sets (space1 = set 1, ...).
# DXIL (Direct3D 12) is compiled at build time on Windows by cmake/CompileShadersDXIL.cmake.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
src="$root/src/render3d/shaders.hlsl"
out="$root/src/render3d/shaders_spirv.inc"
check=0
[[ "${1:-}" == "--check" ]] && check=1

glslang="${GLSLANG:-$(command -v glslangValidator || true)}"
if [[ -z "$glslang" ]]; then
    echo "glslangValidator not found (brew install glslang / apt install glslang-tools)" >&2
    exit 1
fi
spirv_val="$(command -v spirv-val || true)"

# entry point : stage (the list is also in cmake/CompileShadersDXIL.cmake and render3d/shader_blobs.cpp)
entries=(terrain_vs:vert terrain_fs:frag sprite_vs:vert sprite_fs:frag
         model_vs:vert model_shadow_vs:vert model_fs:frag shadow_fs:frag
         terrain2_fs:frag rock_vs:vert rock_fs:frag depth_fs:frag terrain3_fs:frag tonemap_fs:frag)

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

{
    echo "// Generated by tools/compile_shaders.sh from src/render3d/shaders.hlsl - do not edit."
    echo "// $("$glslang" --version | head -1 | sed 's/^ *//')"
    echo "// SPIR-V 1.0 (Vulkan 1.0) modules for SDL_GPU_SHADERFORMAT_SPIRV; included by render3d/shader_blobs.cpp."
} > "$tmp/out.inc"

for e in "${entries[@]}"; do
    name="${e%%:*}"
    stage="${e##*:}"
    "$glslang" -D -V --target-env vulkan1.0 --auto-sampled-textures -S "$stage" \
        -e "$name" --source-entrypoint "$name" -o "$tmp/$name.spv" "$src" > "$tmp/log.txt" 2>&1 || {
        cat "$tmp/log.txt" >&2
        exit 1
    }
    if [[ -n "$spirv_val" ]]; then
        "$spirv_val" --target-env vulkan1.0 "$tmp/$name.spv"
    fi
    size=$(wc -c < "$tmp/$name.spv" | tr -d ' ')
    echo "  $name ($stage): $size bytes"
    {
        echo ""
        echo "alignas(4) inline constexpr unsigned char kSpirv_${name}[] = {"
        od -An -v -tx1 "$tmp/$name.spv" | sed -e 's/^ *//' -e 's/  */ /g' -e '/^$/d' \
            -e 's/\([0-9a-f][0-9a-f]\)/0x\1,/g' -e 's/^/    /' -e 's/, *$/,/'
        echo "};"
    } >> "$tmp/out.inc"
done

if [[ $check -eq 0 ]]; then
    cp "$tmp/out.inc" "$out"
    echo "wrote $out"
fi
